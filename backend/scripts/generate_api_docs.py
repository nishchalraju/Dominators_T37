"""Generate docs/openapi.json and docs/API.md from the running application's own schema.

    python scripts/generate_api_docs.py          # write both files
    python scripts/generate_api_docs.py --check  # exit 1 if they are out of date

The same information is available live at /docs (Swagger UI) and /redoc while the server runs.
"""

import _paths  # noqa: F401
import argparse
import json
import os
import tempfile

# Build the schema against a throw-away database so no real data is touched.
_tmp = tempfile.mkdtemp()
os.environ.setdefault("DATABASE_URL", f"sqlite:///{_tmp}/docs.db")
os.environ.setdefault("STORAGE_DIR", _tmp)
os.environ.setdefault("APP_ENV", "test")

from app.core.config import PROJECT_DIR  # noqa: E402
from app.main import create_app  # noqa: E402

DOCS_DIR = PROJECT_DIR / "docs"


def _resolve(schema: dict, components: dict) -> dict:
    ref = schema.get("$ref")
    return components[ref.rsplit("/", 1)[-1]] if ref else schema


def _type_of(schema: dict, components: dict) -> str:
    if "$ref" in schema:
        return f"[{schema['$ref'].rsplit('/', 1)[-1]}](#{schema['$ref'].rsplit('/', 1)[-1].lower()})"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        parts = [_type_of(s, components) for s in schema["anyOf"] if s.get("type") != "null"]
        return " or ".join(parts) + (" or null" if any(s.get("type") == "null" for s in schema["anyOf"]) else "")
    t = schema.get("type", "object")
    if t == "array":
        return f"array of {_type_of(schema.get('items', {}), components)}"
    if t == "object" and "additionalProperties" in schema and isinstance(schema["additionalProperties"], dict):
        return f"map of {_type_of(schema['additionalProperties'], components)}"
    extras = []
    for key in ("minLength", "maxLength", "minimum", "maximum", "format"):
        if key in schema:
            extras.append(f"{key}={schema[key]}")
    return t + (f" ({', '.join(extras)})" if extras else "")


def _fields(schema: dict, components: dict) -> list[str]:
    schema = _resolve(schema, components)
    required = set(schema.get("required", []))
    lines = ["| Field | Type | Required | Description |", "|---|---|---|---|"]
    for name, prop in schema.get("properties", {}).items():
        desc = (prop.get("description") or "").replace("\n", " ").replace("|", "\\|")
        lines.append(f"| `{name}` | {_type_of(prop, components)} | {'yes' if name in required else 'no'} | {desc} |")
    return lines


def build_markdown(spec: dict) -> str:
    components = spec.get("components", {}).get("schemas", {})
    out = [f"# {spec['info']['title']} - API reference", "", f"Version {spec['info']['version']}. *Generated by `scripts/generate_api_docs.py` from the application's OpenAPI schema - do not edit by hand.*", ""]
    out += [spec["info"].get("description", "").strip(), "", "Live, interactive documentation: `/docs` (Swagger UI) and `/redoc` while the server is running.", ""]
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            by_tag.setdefault(op.get("tags", ["Other"])[0], []).append((method.upper(), path, op))
    tag_order = [t["name"] for t in spec.get("tags", [])] + [t for t in by_tag if t not in {x["name"] for x in spec.get("tags", [])}]
    out += ["## Endpoints", ""]
    for tag in tag_order:
        if tag not in by_tag:
            continue
        out += [f"### {tag}", ""]
        for method, path, op in by_tag[tag]:
            auth = "Bearer token required" if op.get("security") else "no sign-in needed"
            out += [f"#### `{method} {path}`", "", f"**{op.get('summary', '')}** ({auth})", ""]
            if op.get("description"):
                out += [op["description"].strip(), ""]
            params = [p for p in op.get("parameters", [])]
            if params:
                out += ["| Parameter | In | Type | Required | Description |", "|---|---|---|---|---|"]
                for p in params:
                    desc = (p.get("description") or "").replace("\n", " ").replace("|", "\\|")
                    out.append(f"| `{p['name']}` | {p['in']} | {_type_of(p.get('schema', {}), components)} | {'yes' if p.get('required') else 'no'} | {desc} |")
                out.append("")
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                name = body.get("$ref", "").rsplit("/", 1)[-1]
                out += [f"**Request body** ({name}):", ""] + _fields(body, components) + [""]
            out += ["**Responses:** " + ", ".join(f"`{code}` {r.get('description', '')}" for code, r in op["responses"].items()), ""]
    out += ["## Schemas", ""]
    for name, schema in sorted(components.items()):
        if name in ("HTTPValidationError", "ValidationError"):
            continue
        out += [f"### {name}", ""]
        if schema.get("description"):
            out += [schema["description"].strip(), ""]
        out += _fields(schema, components) + [""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = create_app().openapi()
    files = {
        DOCS_DIR / "openapi.json": json.dumps(spec, indent=2, ensure_ascii=False) + "\n",
        DOCS_DIR / "API.md": build_markdown(spec),
    }
    if args.check:
        stale = [p.name for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("Out of date:", ", ".join(stale), "- run: python scripts/generate_api_docs.py")
            return 1
        print("API docs are up to date.")
        return 0
    DOCS_DIR.mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print("Wrote", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
