"""Write datasets/metadata/external_datasets.json: one 'card' per dataset (licence, access, citation, expected folder).

    python scripts/export_dataset_cards.py

The cards come from the same registry the web page shows, so documentation and UI cannot disagree.
No data files are read or downloaded.
"""

import _paths  # noqa: F401
import json
from dataclasses import asdict

from app.core.config import get_settings
from app.services import datasets


def main() -> None:
    cards = [{**asdict(spec), "expected_path": datasets.expected_path(spec)} for spec in datasets.SPECS.values()]
    target = get_settings().datasets_dir / "metadata" / "external_datasets.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    note = "Generated by scripts/export_dataset_cards.py. Facts about the CUHK / NIST / University of Malta pages were read in October 2026: verify the current terms at the source before using any dataset."
    target.write_text(json.dumps({"note": note, "datasets": cards}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {target} ({len(cards)} dataset cards)")


if __name__ == "__main__":
    main()
