"""Write datasets/custom/attribute_sample.schema.json from the controlled vocabulary.

The schema is generated (not hand-edited) so it can never disagree with the code.
    python scripts/generate_dataset_schema.py          # (re)write the file
    python scripts/generate_dataset_schema.py --check  # exit 1 if the file is out of date
"""

import _paths  # noqa: F401
import argparse
import json

from app.core.config import get_settings
from app.services import custom_dataset as cd
from app.services.attributes import ATTRIBUTES, LANGUAGE_CODES, VOCABULARY_VERSION


def build_schema() -> dict:
    props: dict = {
        "sample_id": {"type": "string", "pattern": "^[A-Za-z0-9_.-]{1,64}$", "description": "Unique ID of this row."},
        "group_id": {"type": "string", "pattern": "^[A-Za-z0-9_.-]{0,64}$", "description": "Rows describing the SAME face in different languages share a group_id and must carry identical labels."},
        "split": {"enum": list(cd.SPLITS), "description": "dev = used while building the parser; test = held back."},
        "language": {"enum": list(LANGUAGE_CODES)},
        "description_text": {"type": "string", "minLength": 1, "maxLength": cd.MAX_TEXT, "description": "The witness-style description, in the script of its language."},
    }
    for spec in ATTRIBUTES:
        props[spec.key] = {"enum": ["", *spec.value_keys], "description": f"{spec.label}. Empty = the text does not say (or is contradictory)."}
    props.update(
        translation_review_status={"enum": list(cd.TRANSLATION_STATUSES), "description": "original = English source text; unreviewed / in_review / reviewed = status of a translation."},
        reviewer_id={"type": "string", "description": "Required when translation_review_status is 'reviewed'."},
        reviewed_on={"type": "string", "pattern": "^(\\d{4}-\\d{2}-\\d{2})?$", "description": "YYYY-MM-DD; required when 'reviewed'."},
        annotation_method={"enum": list(cd.ANNOTATION_METHODS)},
        permission_status={"enum": list(cd.PERMISSION_STATUSES), "description": "synthetic_no_real_person = invented text, no real individual involved."},
        image_file={"type": "string", "description": "Optional relative path of an image inside the dataset folder."},
        notes={"type": "string"},
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://sketchassist.local/schemas/attribute_sample.schema.json",
        "title": "SketchAssist AI custom attribute sample (one CSV row)",
        "description": f"Controlled vocabulary version {VOCABULARY_VERSION}. Generated by scripts/generate_dataset_schema.py - do not edit by hand.",
        "type": "object",
        "required": cd.REQUIRED_COLUMNS,
        "additionalProperties": False,
        "properties": props,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"
    path = get_settings().datasets_dir / "custom" / cd.SCHEMA_NAME
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"{path.name} is out of date. Run: python scripts/generate_dataset_schema.py")
            return 1
        print(f"{path.name} is up to date.")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
