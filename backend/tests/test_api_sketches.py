def test_ai_path_labels_and_stores_everything_honestly(client, admin, case_id):
    ai = StandInAI()
    _instances["huggingface"] = ai  # AI_PROVIDER=auto picks the first engine that reports "ready"
    v = generate(client, admin, case_id, engine="ai").json()
    assert v["is_ai_generated"] is True and v["engine"] == "huggingface" and v["model_name"] == "stand-in/model" and "AI" in v["engine_label"]
    v2 = revise(client, admin, v["id"], "add glasses").json()  # defaults to the AI engine because the parent is AI
    assert v2["is_ai_generated"] is True and ai.edits and ai.edits[0].change_summary_en == "Glasses: Wearing glasses"
    free = revise(client, admin, v2["id"], "add a scar on the left cheek").json()  # free text is allowed for AI engines
    assert free["is_ai_generated"] is True and any("free text" in n for n in free["notes"])
    stats = client.get("/api/dashboard", headers=admin).json()
    assert stats["ai_versions"] == 3 and stats["schematic_versions"] == 0
    band = Image.open(io.BytesIO(client.get(v["download_url"], headers=admin).content))
    assert band.size[1] > 1024


