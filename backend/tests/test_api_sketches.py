def test_revision_creates_a_new_version_and_never_touches_the_old_one(client, admin, case_id):
    v1 = generate(client, admin, case_id).json()
    before = sha(client, admin, v1["id"])
    r = revise(client, admin, v1["id"], "make the eyebrows thicker and add glasses")
    v2 = r.json()
    assert r.status_code == 201 and v2["version_number"] == 2 and v2["kind"] == "revision"
    assert v2["parent_id"] == v1["id"] and v2["parent_version_number"] == 1
    assert v2["attributes"]["eyebrows"] == "thick" and v2["attributes"]["glasses"] == "glasses"
    changes = {c["attribute"]: (c["before"], c["after"]) for c in v2["revision_details"]["changes"]}
    assert changes == {"eyebrows": ("medium", "thick"), "glasses": ("none", "glasses")}
    assert v2["instruction"] == "make the eyebrows thicker and add glasses" and v2["instruction_language"] == "en"
    assert sha(client, admin, v2["id"]) != before  # the picture really changed
    assert sha(client, admin, v1["id"]) == before  # and the earlier one is byte-for-byte unchanged
    assert client.get(f"/api/sketch-versions/{v1['id']}", headers=admin).json()["attributes"]["eyebrows"] == "medium"


def test_each_revision_of_each_kind_changes_the_image(client, admin, case_id):
    v = generate(client, admin, case_id, {**ATTRS, "face_shape": "oval"}).json()
    seen = {sha(client, admin, v["id"])}
    for text in ["make the nose broader", "make the face rounder", "make the hair longer", "add glasses", "make the eyebrows thinner",
                 "ಗಡ್ಡ ಸೇರಿಸಿ"]:
        r = revise(client, admin, v["id"], text, "kn" if text.startswith("ಗಡ್ಡ") else "en")
        assert r.status_code == 201, (text, r.text)
        digest = sha(client, admin, r.json()["id"])
        assert digest not in seen, text
        seen.add(digest)
    items = client.get("/api/sketch-versions", headers=admin, params={"case_id": case_id}).json()["items"]
    assert [i["version_number"] for i in items] == list(range(1, 8))  # numbers are never reused or skipped


