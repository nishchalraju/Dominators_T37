def sha(client, headers, sketch_id) -> str:
    r = client.get(f"/api/sketch-versions/{sketch_id}/image", headers=headers)
    assert r.status_code == 200 and r.headers["content-type"] == "image/png"
    return hashlib.sha256(r.content).hexdigest()


def revise(client, headers, sketch_id, text, language="en", engine=None):
    body = {"instruction": text, "language": language}
    if engine:
        body["engine"] = engine
    return client.post(f"/api/sketches/{sketch_id}/revise", headers=headers, json=body)


class StandInAI(SketchModel):
    """Test-only stand-in for an AI engine. Production code never contains a mock like this."""

    engine, label, is_ai = "huggingface", "Stand-in AI (tests only)", True

    def __init__(self):
        self.edits = []

    def status(self):
        return model_base.ModelStatus(engine=self.engine, label=self.label, is_ai=True, state="ready", detail="test")

    def generate(self, request):
        return ModelOutput(png=render_schematic({**request.attributes, "hair_style": "wavy"}).png, engine=self.engine, is_ai_generated=True,
                           model_name="stand-in/model", prompt_used="a prompt", notes=["Generated by a stand-in AI."])

    def edit(self, request):
        self.edits.append(request)
        return ModelOutput(png=render_schematic(request.new_attributes).png, engine=self.engine, is_ai_generated=True,
                           model_name="stand-in/model", prompt_used="edit prompt", notes=["Edited by a stand-in AI."])


