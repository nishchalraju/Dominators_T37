def test_selection_is_exclusive_and_does_not_change_images(client, admin, case_id):
    v1 = generate(client, admin, case_id).json()
    v2 = revise(client, admin, v1["id"], "add glasses").json()
    assert v2["is_selected"] is True
    assert client.post(f"/api/sketch-versions/{v1['id']}/select", headers=admin).json()["is_selected"] is True
    items = client.get("/api/sketch-versions", headers=admin, params={"case_id": case_id}).json()["items"]
    assert [i["is_selected"] for i in items] == [True, False]
    assert client.get(f"/api/cases/{case_id}", headers=admin).json()["selected_sketch_id"] == v1["id"]
    v3 = revise(client, admin, v1["id"], "make the nose broader").json()  # branching from an older version
    assert v3["parent_version_number"] == 1 and v3["version_number"] == 3


def test_download_adds_a_provenance_band_without_changing_the_stored_file(client, admin, case_id):
    v = generate(client, admin, case_id).json()
    stored = client.get(v["image_url"], headers=admin).content
    d = client.get(v["download_url"], headers=admin)
    assert d.status_code == 200 and "attachment" in d.headers["content-disposition"] and ".png" in d.headers["content-disposition"]
    band = Image.open(io.BytesIO(d.content))
    assert band.size[0] == 1024 and band.size[1] > 1024  # extra caption band below the picture
    assert client.get(v["image_url"], headers=admin).content == stored


def test_tampered_image_files_are_refused(client, admin, case_id, env):
    v = generate(client, admin, case_id).json()
    path = next((Path(env) / "storage" / "sketches").rglob("*.png"))
    path.write_bytes(path.read_bytes() + b"tampered")
    r = client.get(v["image_url"], headers=admin)
    assert r.status_code == 500 and r.json()["code"] == "image_integrity_failed"
    path.unlink()
    assert client.get(v["image_url"], headers=admin).status_code == 410


